import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const src=readFileSync('worker_notify_v130.js','utf8');
const start=src.indexOf('const read=async(name,path,params)=>');
const end=src.indexOf('const [stats,events,odds,half]',start);
assert(start>=0&&end>start);
const make=new Function('api','errText','return async()=>{const health={},sourceWarnings=[];'+src.slice(start,end)+'return {read,health,sourceWarnings};}');
const providerError=async(path,params,strict)=>{if(strict)throw Error('API_PROVIDER_RATE_LIMIT');return [];};
const failed=await make(providerError,e=>e.message)();
assert.deepEqual(await failed.read('stats','/fixtures/statistics',{fixture:1}),[]);
assert.equal(failed.health.stats,'ERROR','HTTP 200 provider rate error must not become a valid empty statistics feed');
assert.deepEqual(failed.sourceWarnings,['stats:API_PROVIDER_RATE_LIMIT']);
const half=await make(providerError,e=>e.message)();
await half.read('half','/fixtures/statistics',{fixture:1,half:true});
assert.equal(half.health.half,'ERROR');
const empty=await make(async()=>[],e=>e.message)();
await empty.read('stats','/fixtures/statistics',{fixture:1});
assert.equal(empty.health.stats,'EMPTY','Genuine zero statistics must remain EMPTY, not ERROR');
assert.deepEqual(empty.sourceWarnings,[]);
const success=await make(async()=>[{team:{id:1},statistics:[{type:'Shots on Goal',value:3}]}],e=>e.message)();
const rows=await success.read('stats','/fixtures/statistics',{fixture:1});
assert.equal(success.health.stats,'OK');assert.equal(rows[0].statistics[0].value,3);
const optional=await make(async(path,params,strict)=>{assert.equal(strict,false);return [];},e=>e.message)();
await optional.read('events','/fixtures/events',{fixture:1});
await optional.read('odds','/odds/live',{fixture:1});
assert.equal(optional.health.events,'EMPTY');assert.equal(optional.health.odds,'EMPTY');
console.log('PASS: provider errors distinguished from valid empty statistics; optional feeds retain tolerant behavior');

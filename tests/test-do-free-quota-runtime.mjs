import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const source=readFileSync(new URL('../worker_notify_v137_quota50000.js',import.meta.url),'utf8');
const start=source.indexOf('  async reserveApiCall(){');
const end=source.indexOf('  async quotaStatus(){',start);
assert.ok(start>=0&&end>start);
const method=source.slice(start,end);
const num=(v,d=0)=>Number.isFinite(Number(v))?Number(v):d;
const n=num;
const writes=[];
const day=new Date().toISOString().slice(0,10);
const key='api:q50000:global:v1';
let saved={day,used:3,limit:3,updated:1};
const ctx={storage:{get:async()=>structuredClone(saved),put:async(k,v)=>{writes.push(k);saved=structuredClone(v)}}};
const obj=vm.runInNewContext('({'+method+'})',{Date,n,Error});
obj.ctx=ctx;obj.quotaCfg=()=>({total:3});obj.quotaWork=fn=>fn();
for(let i=0;i<10;i++)await assert.rejects(obj.reserveApiCall(),/API_TOTAL_DAILY_BUDGET_REACHED/);
assert.equal(writes.length,0,'rejected reservations must not write');
saved.used=2;
await obj.reserveApiCall();
assert.equal(writes.length,1,'accepted reservation must persist exactly once');
assert.equal(saved.used,3,'accepted reservation increments counter');
await assert.rejects(obj.reserveApiCall(),/API_TOTAL_DAILY_BUDGET_REACHED/);
assert.equal(writes.length,1,'exhausted budget remains hard blocked');
console.log('PASS: quota exhaustion no-write; accepted calls counted and hard cap enforced');

import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const source=readFileSync(new URL('../worker_notify_v137_quota50000.js',import.meta.url),'utf8');
const begin=source.indexOf('  d1LiveEnabled(){');
const end=source.indexOf('  async reserveApiCall(){',begin);
assert.ok(begin>0&&end>begin);
const methods=source.slice(begin,end).replace(/\}\n  async /g,'},\n  async ').replace(/\}\n  d1LiveEnabled/g,'},\n  d1LiveEnabled');
const rows=new Map(),legacy=new Map();
let creates=0,reads=0,writes=0,listReads=0,failWrite=false;
const db={prepare(sql){return {bind(...args){return {...this,args}},async run(){if(sql.startsWith('CREATE')){creates++;return};if(sql.startsWith('INSERT')){if(failWrite)throw Error('D1_WRITE_FAILED');writes++;rows.set(this.args[0],{fixture_id:this.args[0],payload:this.args[1]});return};if(sql.startsWith('DELETE')){rows.delete(this.args[0]);return}},async first(){reads++;return rows.get(this.args[0])||null},async all(){listReads++;return {results:[...rows.values()]}}}}};
const storage={async list(){return new Map([...legacy].map(([id,row])=>['notify:match:'+id,row]))},async get(key){return legacy.get(Number(key.split(':').at(-1)))||null},async put(key,value){legacy.set(Number(key.split(':').at(-1)),structuredClone(value))},async delete(key){legacy.delete(Number(key.split(':').at(-1)))} };
const make=(enabled=true)=>{const o=vm.runInNewContext('({'+methods+'})',{String,Number,Date,JSON,Map,Error});o.env={LIVE_STATE_D1_ENABLED:String(enabled),FOOTBALL_DB:db};o.ctx={storage};return o};
const old={id:10,history:[{minute:33}],alerts:{'device:H1':{armed:false,lastSent:123}},lastAt:10};
legacy.set(10,structuredClone(old));
let o=make();
assert.equal((await o.getNotifyMatch(10)).history[0].minute,33,'legacy state readable before migration');
await o.putNotifyMatch(10,{...old,lastAt:20});
assert.equal(legacy.get(10).lastAt,10,'legacy data must remain untouched');
o=make(); // simulate Durable Object restart
assert.equal((await o.getNotifyMatch(10)).lastAt,20,'D1 survives restart');
assert.equal((await o.getNotifyMatch(10)).alerts['device:H1'].lastSent,123,'dedup ledger survives restart');
assert.equal((await o.listNotifyMatches()).length,1,'merge must not duplicate legacy+D1');
const loaded=listReads;
for(let i=0;i<100;i++)await o.listNotifyMatches();
assert.equal(listReads,loaded,'warm scanner must not repeatedly scan accumulated tombstones');
const copy=await o.getNotifyMatch(10);copy.history.push({minute:99});
assert.equal((await o.getNotifyMatch(10)).history.length,1,'mutating a read cannot mutate durable cache');
failWrite=true;await assert.rejects(o.putNotifyMatch(10,{...old,lastAt:999}),/D1_WRITE_FAILED/);failWrite=false;
assert.equal((await o.getNotifyMatch(10)).lastAt,20,'failed durable write cannot advance cache');
await o.deleteNotifyMatch(10);
assert.equal((await o.getNotifyMatch(10)),null,'delete cannot resurrect old state');
assert.equal(writes,2,'D1 insert and tombstone are durable writes');
assert.ok(legacy.has(10),'original DO row must remain available for rollback');
const noD1=make(false);await noD1.putNotifyMatch(11,{id:11,history:[],alerts:{}});
assert.ok(legacy.has(11),'disabled mode keeps original storage');
assert.equal(rows.has(11),false,'disabled mode never writes D1');
console.log('PASS: D1 opt-in, legacy fallback, restart, signal history, alert dedup, no resurrection');

import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const source=readFileSync(new URL('../worker_notify_v135_full_pause.js',import.meta.url),'utf8');
const start=source.indexOf('  async alarm(){');
const end=source.indexOf('  async fetch(request){',start);
assert.ok(start>=0&&end>start);
const alarm=source.slice(start,end);
let state={},writes=0,superCalls=0;
const ctx={storage:{get:async()=>state,put:async(k,v)=>{assert.equal(k,'notify:status');state=v;writes++}}};
const obj=vm.runInNewContext('({'+alarm+'})',{Date,Number});
obj.ctx=ctx;obj.scanControl=async()=>({enabled:false,updated:123});
for(let i=0;i<10;i++)await obj.alarm();
assert.equal(writes,1,'repeated pause alarms must not write repeatedly');
assert.equal(superCalls,0);
assert.equal(state.paused,true);
obj.scanControl=async()=>({enabled:false,updated:456});
await obj.alarm();
assert.equal(writes,2,'new pause transition should persist');
console.log('PASS: repeated pause alarms do not write; changed pause state persists');

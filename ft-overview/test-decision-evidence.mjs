import assert from 'node:assert/strict';
import {freezeFTDecision,settleFTEvidence} from './decision-evidence.mjs';
const at=1800000000000,sourceCommit='a'.repeat(40);
const s={id:1,revision:1,at,minute:65,status:'2H',goals:{home:1,away:0},metrics:{sot:2},market:{line:1.75,over:2.1,at,score:{home:1,away:0},period:'FT',basis:'FULL_MATCH'},model:{at,version:'test',kind:'RESEARCH',independent:true,pmf:[.4,.4,.2]}};
const options={decisionAt:at+1000,sourceCommit},a=freezeFTDecision(s,options);
assert.equal(a.json,freezeFTDecision(s,options).json);
const r=JSON.parse(a.json);assert.equal(r.decision.action,'TRIAL_OVER');assert.equal(r.raw_market,null);
s.goals.home=5;assert.equal(JSON.parse(a.json).observation.goals.home,1);s.goals.home=1;
const f={fixture_id:1,status:'FT',received_at:at+3600000,regulation_score:{home:2,away:0}};
assert.equal(settleFTEvidence(a.json,f).profit_per_unit,.55);
assert.equal(settleFTEvidence(a.json,{...f,regulation_score:undefined}).state,'PENDING');
assert.equal(settleFTEvidence(a.json,{...f,fixture_id:2}).state,'PENDING');
assert.equal(settleFTEvidence(a.json,{...f,regulation_score:{home:0,away:0}}).state,'REVIEW_SCORE_CORRECTION');
assert.equal(settleFTEvidence(a.json,{...f,status:'AET',goals:{home:5,away:0}}).profit_per_unit,.55);
assert.throws(()=>freezeFTDecision({...s,contextAt:at+2000},options),/FUTURE_SOURCE/);
assert.throws(()=>freezeFTDecision(s,{...options,maxBytes:10}),/EVIDENCE_TOO_LARGE/);
const missing=freezeFTDecision({...s,market:null},options);assert.equal(JSON.parse(missing.json).decision.action,'WAIT_PRICE');
const negative=freezeFTDecision({...s,market:{...s.market,over:1.5}},options);assert.equal(JSON.parse(negative.json).decision.action,'WAIT_PRICE');
assert.equal(settleFTEvidence(missing.json,f).state,'FINAL_NO_PRICED_DECISION');
console.log('FT_V2_EXACT_DECISION_EVIDENCE_PASS; serializer only, no persistence or real outcomes');
